/** The genre a number names, or undefined. */
export function genreName(n: number): string | undefined {
  return GENRES[n];
}

/**
 * An ID3v2 `TCON` value as a name: "(17)" and "17" are numbers, "(17)Rock" keeps the text, "(RX)" is Remix and
 * "(CR)" Cover, anything else is the name itself.
 */
export function id3Genre(value: string): string {
  const v = value.trim();
  if (/^\d+$/.test(v)) return genreName(Number(v)) ?? v;
  const m = /^\((\d+|RX|CR)\)(.*)$/.exec(v);
  if (!m) return v;
  const rest = (m[2] ?? '').trim();
  if (rest) return rest;
  if (m[1] === 'RX') return 'Remix';
  if (m[1] === 'CR') return 'Cover';
  return genreName(Number(m[1])) ?? v;
}
